local translator = {}
setmetatable(translator, {
    __call = function(_, msgid)
        return translations[msgid] or base_gettext(msgid)
    end,
})

translator.ngettext = function(singular, plural, n)
    if singular == "%1 file" and plural == "%1 files" then return "%1 fájl" end
    if singular == "file" and plural == "files" then return "fájl" end
    if singular == "book" and plural == "books" then return n == 1 and "könyv" or "könyv" end
    if singular == "Delete %1 item?" and plural == "Delete %1 items?" then
        return n == 1 and "Törlöd a kijelölt elemet?" or "Törlöd a kijelölt %1 elemet?"
    end
    if singular == "%1 file in total." and plural == "%1 files in total." then return "Összesen %1 fájl." end
    local original = base_gettext.ngettext(singular, plural, n)
    return translations[original] or original
end

return translator
