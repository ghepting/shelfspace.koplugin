// Turns the lab's spec.json into art/spec.lua (the geometry the shelf module composes the pieces from).
// Usage: node tools/art/spec2lua.js spec.json > shelfspace.koplugin/art/spec.lua
const spec = JSON.parse(require("fs").readFileSync(process.argv[2], "utf8"));
const lua = (v, ind) => {
  const pad = "  ".repeat(ind + 1), end = "  ".repeat(ind);
  if (Array.isArray(v)) {
    if (v.every(x => typeof x === "number")) return "{ " + v.join(", ") + " }";
    return "{\n" + v.map(x => pad + lua(x, ind + 1) + ",").join("\n") + "\n" + end + "}";
  }
  if (v && typeof v === "object") {
    const keys = Object.keys(v);
    const flat = keys.every(k => typeof v[k] !== "object");
    const kv = k => (/^[A-Za-z_]\w*$/.test(k) ? k : `["${k}"]`) + " = " + lua(v[k], ind + 1);
    if (flat) return "{ " + keys.map(kv).join(", ") + " }";
    return "{\n" + keys.map(k => pad + kv(k) + ",").join("\n") + "\n" + end + "}";
  }
  return typeof v === "string" ? JSON.stringify(v) : String(v);
};
console.log("-- Generated by tools/art/spec2lua.js from the Shelf Piece Lab's spec.json: where each layer of each piece goes, in art units (2 px each).\nreturn " + lua(spec, 0));
